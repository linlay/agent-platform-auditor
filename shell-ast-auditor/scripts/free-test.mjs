import { chromium, expect } from "@playwright/test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

const origin = process.env.AUDITOR_URL ?? "http://127.0.0.1:8093";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const errors = [], checks = [];
fs.mkdirSync("artifacts", { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1366, height: 1000 } });
  await page.addInitScript(() => localStorage.setItem("shell-ast-auditor.project-dir.v1", ""));
  page.on("pageerror", e => errors.push(String(e)));
  await page.goto(origin);
  await page.getByRole("heading", { name: "bash.pipeline", exact: true }).waitFor();
  const nav = name => page.locator(".sections").getByRole("button", { name, exact: true });
  await page.getByLabel("单用例模式", { exact: true }).selectOption("syntax-only");
  const runResponse = page.waitForResponse(r => r.url().endsWith("/api/runs") && r.request().method() === "POST");
  await page.getByRole("button", { name: "解析当前", exact: true }).click();
  const saved = await (await runResponse).json();
  const savedItem = page.locator('aside .case[data-case-id="bash.pipeline"]');
  await expect(savedItem.locator(".judgment-green")).toHaveCount(1);
  await expect(nav("自由测试")).toBeEnabled();
  await nav("自由测试").click();
  assert.equal(await page.getByLabel("测试集", { exact: true }).count(), 0);
  assert.equal(await page.locator("aside,.batch-line").count(), 0);
  const input = page.getByLabel("自定义命令", { exact: true });
  const parse = page.getByRole("button", { name: "解析命令", exact: true });
  await expect(input).toHaveValue("node --version");
  assert.equal(await page.getByLabel("自由测试 Shell", { exact: true }).locator("option").count(), 10);
  await input.fill(" \n\t"); await expect(parse).toBeDisabled();
  await page.getByLabel("自由测试 Shell", { exact: true }).selectOption("bash-5.2");
  const sentinel = path.resolve(`artifacts/free-mode-never-execute-${Date.now()}`);
  const command = `printf '%s\\n' "中文  空格"\nnode --version; touch '${sentinel}'`;
  await input.fill(command);
  let runPosts = 0;
  page.on("request", r => { if (r.url().endsWith("/api/runs") && r.method() === "POST") runPosts++; });
  let response = page.waitForResponse(r => r.url().endsWith("/api/parse") && r.request().method() === "POST");
  await input.press("Control+Enter");
  let http = await response, actual = await http.json();
  assert.equal(http.request().postDataJSON().command, command);
  assert.equal(http.request().postDataJSON().review.mode, "classification");
  assert.equal(http.request().postDataJSON().review.accessLevel, undefined);
  assert.equal(actual.input.profile, "bash-5.2");
  assert.equal(actual.input.command, command);
  await expect(page.getByRole("heading", { name: "解析结果", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "仅分析行为分类", exact: true })).toBeVisible();
  assert.equal(await page.locator(".free-test .case-meta").getByText(/预期语法/).count(), 0);
  assert.equal(await page.locator(".free-test .judgment-green").count(), 0);
  assert.equal(fs.existsSync(sentinel), false);
  checks.push("third mode has no testset/batch UI; 10 profiles; blank input disabled; multiline/Unicode preserved; classification omits access level; command body never executes");

  await page.getByRole("button", { name: "导出报告", exact: true }).click();
  const pending = page.waitForEvent("download");
  await page.getByRole("button", { name: "完整数据", exact: true }).click();
  const downloaded = await pending;
  const exported = JSON.parse(fs.readFileSync(await downloaded.path(), "utf8"));
  assert.equal(exported.scope, "free"); assert.equal(exported.cases.length, 1);
  assert.equal(exported.cases[0].expect, null);
  assert.equal(exported.results.custom.input.command, command);
  assert.equal(exported.results.custom.parser.sha256, actual.parser.sha256);
  await input.fill("node --version");
  await expect(page.locator(".free-stale")).toBeVisible();
  await nav("单用例测试").click();
  await expect(savedItem.locator(".judgment-green")).toHaveCount(1);
  assert.equal(await page.locator('aside .case[data-case-id="custom"]').count(), 0);
  const workspace = await page.evaluate(() => JSON.parse(localStorage.getItem("shell-ast-auditor.manual-results.v1")));
  assert.equal(workspace.sets["shell-core"]["bash.pipeline"].result.runId, saved.id);
  assert.equal(workspace.sets["shell-core"].custom, undefined);
  await nav("自由测试").click();
  await expect(input).toHaveValue("node --version");
  await expect(page.locator(".source")).toHaveText(command);
  checks.push("free draft/result survive mode switches; single-case result and cache remain intact; export contains only the free result and captured parser provenance");

  await page.getByLabel("自定义审查模式", { exact: true }).selectOption("evaluation");
  await page.getByLabel("自定义权限档位", { exact: true }).selectOption("auto_approve");
  await page.route("**/api/parse", async route => { await new Promise(resolve => setTimeout(resolve, 300)); await route.continue(); });
  response = page.waitForResponse(r => r.url().endsWith("/api/parse") && r.request().method() === "POST");
  await parse.click(); await expect(nav("单用例测试")).toBeDisabled();
  http = await response; actual = await http.json();
  assert.equal(actual.report.policy.accessLevel, "auto_approve");
  await expect(page.locator(".policy-panel .decision")).toBeVisible();
  await expect(nav("单用例测试")).toBeEnabled();
  await page.getByRole("button", { name: "清空结果", exact: true }).click();
  assert.equal(await page.locator(".free-test .inspector").count(), 0);
  await expect(input).toHaveValue("node --version");
  await page.getByLabel("自定义审查模式", { exact: true }).selectOption("syntax-only");
  await input.fill("echo 'unterminated");
  response = page.waitForResponse(r => r.url().endsWith("/api/parse") && r.request().method() === "POST");
  await parse.click(); http = await response; actual = await http.json();
  assert.equal(actual.report.status.syntax, "invalid");
  assert.equal(http.request().postDataJSON().review.mode, "syntax-only");
  await expect(page.locator(".parse-status").getByText("语法无效", { exact: true })).toBeVisible();
  await expect(page.getByRole("tab", { name: "执行面", exact: true })).toHaveAttribute("aria-selected", "true");
  checks.push("evaluation uses selected access level; pending parse disables duplicate work/navigation; clear affects only free result; invalid syntax is displayed as an observation without invented test expectations");

  await page.getByLabel("自定义审查模式", { exact: true }).selectOption("evaluation");
  await input.fill("node --version");
  response = page.waitForResponse(r => r.url().endsWith("/api/parse") && r.request().method() === "POST");
  await parse.click(); await response;
  await expect(nav("单用例测试")).toBeEnabled();
  await page.screenshot({ path: "artifacts/ui-free-test.png", fullPage: true });
  await page.emulateMedia({ colorScheme: "dark" });
  await page.screenshot({ path: "artifacts/ui-free-test-dark.png", fullPage: true });
  await page.emulateMedia({ colorScheme: "light" });
  for (const width of [1366, 1024, 760, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    assert.equal(await page.locator("main").evaluate(e => e.scrollWidth > e.clientWidth), false, "main overflow at " + width);
    const header = await page.locator(".app-header").boundingBox();
    const freeNav = await nav("自由测试").boundingBox();
    assert.ok(freeNav.y >= header.y && freeNav.y + freeNav.height <= header.y + header.height, "navigation clipped at " + width);
    if (width === 390) await page.screenshot({ path: "artifacts/ui-free-test-mobile.png", fullPage: true });
  }
  assert.equal(runPosts, 0);
  assert.equal(fs.existsSync(sentinel), false);
  assert.deepEqual(errors, []);
  checks.push("desktop/dark/mobile layouts at 1366/1024/760/390/320px; third tab remains visible; free parsing creates no test batches");
  const evidence = { at: new Date().toISOString(), checks, originalManualRun: saved.id, pageErrors: errors };
  fs.writeFileSync("artifacts/free-test-validation.json", JSON.stringify(evidence, null, 2));
  console.log("PASS " + JSON.stringify(evidence));
} finally { await browser.close(); }
